#Calcula Volume de uma caixa retangular
# Definindo as variáveis
comprimento = 5.0  # em metros
largura = 3.0      # em metros
altura = 2.0       # em metros
# Calculo do volume
volume = comprimento * largura * altura
# Exibindo o resultado
print(f"O volume da caixa retangular é: {volume:.2f} metros cúbicos")
# Exibindo o resultado em litros
print(f"O volume da caixa retangular é: {volume * 1000:.2f} litros")